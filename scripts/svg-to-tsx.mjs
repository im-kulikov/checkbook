#!/usr/bin/env node
// design/assets/illustrations/*.svg -> src/ui/illustrations/*.tsx (Preact components) + index.ts (name -> component).
// Runs from `npm run illustrations` (before dev, typecheck, test, build); the output is generated, not committed.
//   node scripts/svg-to-tsx.mjs [srcDir] [outDir]
// SVG is inlined as JSX so CSS variables of the page apply in both themes (no <img>, no innerHTML: NFR-S4, CSP).
// Attributes become camelCase (stroke-width -> strokeWidth; aria-* and data-* stay), the root gets aria-hidden="true".
// No dependencies, Node 22+.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { pathToFileURL } from 'node:url'

const TAG = /<(\/?)([a-zA-Z][\w:-]*)((?:\s+[^\s=/>]+(?:\s*=\s*(?:"[^"]*"|'[^']*'))?)*)\s*(\/?)>/g
const ATTR = /([^\s=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'))?/g
const camel = (a) => (/^(aria|data)-/.test(a) ? a : a.replace(/[-:]([a-z])/g, (_, c) => c.toUpperCase()))
export const pascal = (name) => name.replace(/(^|[-_])([a-z0-9])/g, (_, __, c) => c.toUpperCase())

/** One SVG text -> the source of a .tsx module exporting `<Name>`. Throws on anything unsafe or unexpected. */
export function convert(svg, name) {
  const clean = svg.replace(/<\?[\s\S]*?\?>|<!--[\s\S]*?-->|<!DOCTYPE[^>]*>/g, '').trim()
  if (clean.replace(TAG, '').trim()) throw new Error(`${name}: text inside SVG is not supported`)
  let first = true
  const jsx = clean.replace(TAG, (_, close, tag, attrs, self) => {
    if (close) return `</${tag}>`
    if (/^(script|style|foreignObject|image)$/i.test(tag)) throw new Error(`${name}: <${tag}> is not allowed`)
    if (first && tag !== 'svg') throw new Error(`${name}: the root must be <svg>`)
    const out = []
    for (const [, key, dq, sq] of attrs.matchAll(ATTR)) {
      const value = dq ?? sq ?? ''
      if (key === 'style' || /^on/i.test(key)) throw new Error(`${name}: attribute ${key} is not allowed`)
      if (/href$/i.test(key) && !value.startsWith('#')) throw new Error(`${name}: external ${key} is not allowed`)
      if (first && /^(aria-hidden|focusable)$/.test(key)) continue // re-added below, after the props
      out.push(/["\n]/.test(value) ? `${camel(key)}={${JSON.stringify(value)}}` : `${camel(key)}="${value}"`)
    }
    if (first) out.push('{...props}', 'aria-hidden="true"', 'focusable="false"')
    first = false
    return `<${tag}${out.map((a) => ' ' + a).join('')}${self ? ' /' : ''}>`
  })
  if (first) throw new Error(`${name}: no <svg>`)
  return `// Generated by scripts/svg-to-tsx.mjs from design/assets/illustrations/${name}.svg. Do not edit.
import type { JSX } from 'preact'

export function ${pascal(name)}(props: JSX.SVGAttributes<SVGSVGElement>) {
  return (
    ${jsx}
  )
}
`
}

export function convertDir(srcDir = 'design/assets/illustrations', outDir = 'src/ui/illustrations') {
  const names = readdirSync(srcDir)
    .filter((f) => f.endsWith('.svg') && !f.endsWith('-dark.svg')) // no separate dark files: colors are CSS variables
    .map((f) => basename(f, '.svg'))
    .sort()
  mkdirSync(outDir, { recursive: true })
  for (const n of names)
    writeFileSync(join(outDir, `${n}.tsx`), convert(readFileSync(join(srcDir, `${n}.svg`), 'utf8'), n))
  const index = `// Generated by scripts/svg-to-tsx.mjs. Do not edit.
${names.map((n) => `import { ${pascal(n)} } from './${n}'`).join('\n')}

export const illustrations = {
${names.map((n) => `  '${n}': ${pascal(n)},`).join('\n')}
} as const
export type IllustrationName = keyof typeof illustrations
`
  writeFileSync(join(outDir, 'index.ts'), index)
  return names
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const names = convertDir(process.argv[2], process.argv[3])
  console.log(`svg-to-tsx: ${names.length} illustrations`)
}
